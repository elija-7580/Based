    static func search(_ query: String, limit: Int = 60) -> [(String, String)] {
        let q = query.lowercased().trimmingCharacters(in: .whitespaces)
        guard !q.isEmpty else { return Array(all.prefix(limit)) }
        let prefix = all.filter { $0.1.split(separator: " ").contains { $0.hasPrefix(q) } }
        let rest = all.filter { e in e.1.contains(q) && !prefix.contains { $0.0 == e.0 } }
        return Array((prefix + rest).prefix(limit))
    }

    static func random() -> String {
        let pool = ["📝", "📚", "🚀", "💡", "🎯", "📌", "🌱", "🧠", "📅", "✨", "🔥", "📓", "🗂️", "🧩", "🎨", "☕"]
        return pool.randomElement() ?? "📝"
    }
